#!/usr/bin/env python3
"""License audit for the bundled board library (app/data).

    python3 tools/license_audit.py            write BOARDS.md (attribution for every bundled board)
    python3 tools/license_audit.py --prune    also remove boards whose source repository states no license

A repository with no license is "all rights reserved", so its board data must not be redistributed here.
Pruned boards are listed in tools/unlicensed.json; to bring one back, confirm its license, set "license"
for it in that file and re-import it with tools/build.py / tools/import2.py.
"""
import argparse, json, os

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
APP = os.path.join(ROOT, 'app')
INDEX = os.path.join(APP, 'data', 'index.json')
NO_LICENSE = {None, '', 'NONE', 'NOASSERTION'}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--prune', action='store_true')
    a = ap.parse_args()
    with open(INDEX, encoding='utf-8') as h:
        repos = json.load(h)

    if a.prune:
        keep, drop = [], []
        for r in repos:
            (drop if r.get('license') in NO_LICENSE else keep).append(r)
        for r in drop:
            names = {r['id']} | {b['id'] for b in r.get('boards', [])}
            for b in r.get('boards', []):
                for v in b.get('versions', []):
                    f = v.get('file')
                    if f:
                        for p in (f, f.replace('.json.gz.txt', '.meta.json')):
                            fp = os.path.join(APP, p)
                            if os.path.isfile(fp): os.remove(fp)
            for d in ('photos', 'thumbs'):
                for fn in os.listdir(os.path.join(APP, d)):
                    if os.path.splitext(fn)[0] in names:
                        os.remove(os.path.join(APP, d, fn))
        if drop:
            with open(os.path.join(ROOT, 'tools', 'unlicensed.json'), 'w', encoding='utf-8') as h:
                json.dump([{'id': r['id'], 'url': r['url'], 'license': None, 'note': 'no license found in the repository'} for r in drop], h, indent=1)
            with open(INDEX, 'w', encoding='utf-8') as h:
                json.dump(keep, h, ensure_ascii=False, separators=(',', ':'))
        print(f'pruned {len(drop)} boards without a license: ' + ', '.join(r['id'] for r in drop))
        repos = keep

    lines = ['# Bundled boards', '',
             'Converted from the source repositories below. Each design keeps its original license and copyright.',
             'Share-alike licenses (CERN-OHL-S, CC-BY-SA, GPL) apply to derived designs; CC-BY-NC-SA forbids commercial use.',
             'Removal or attribution requests: open an issue. Generated by `tools/license_audit.py`.', '',
             '| Board | Author | License | Source | Commit |', '| --- | --- | --- | --- | --- |']
    for r in sorted(repos, key=lambda r: r['title'].lower()):
        lic = r.get('license') or '?'
        if lic == 'see LICENSE': lic = 'see the repository LICENSE'
        title = r['title'].replace('|', '\\|')
        lines.append(f"| {title} | {r.get('owner', '')} | {lic} | [{r['url'].replace('https://', '')}]({r['url']}) | `{r.get('head', '')}` |")
    with open(os.path.join(ROOT, 'BOARDS.md'), 'w', encoding='utf-8') as h:
        h.write('\n'.join(lines) + '\n')
    print(f'wrote BOARDS.md ({len(repos)} boards)')


if __name__ == '__main__':
    main()
