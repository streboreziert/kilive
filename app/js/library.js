/* KiLive — shared library of user-made boards (db capability) and local drafts */
(function () {
  'use strict';
  const N = window.Noeti;

  const CHUNK = 240000;          // base64 characters per blob document (docs are capped at 256 KiB)
  const MAX_BLOB = 6.5e6;        // compressed bytes we are willing to store for one board
  const DRAFT_KEY = 'drafts';

  const L = (N.lib = {
    ready: false, live: false, db: null, uid: null, canWrite: false,
    catalog: new Map(),          // uid -> {boards: {bid: meta}}
    thumbs: new Map(),           // bid -> Promise<dataURL|null>
    drafts: new Map(),           // id -> draft (memory; design drafts are mirrored to localStorage)
  });

  // ------------------------------------------------------------------ ids + encoding
  L.newId = prefix => (prefix || 'b') + Date.now().toString(36) + Math.random().toString(36).slice(2, 6);
  L.repoId = bid => 'u-' + bid;
  L.draftRepoId = id => 'draft-' + id;

  async function gzip(text) {
    if (typeof CompressionStream === 'undefined') throw new Error('This browser cannot compress board data. Update to a current browser.');
    const s = new Blob([text]).stream().pipeThrough(new CompressionStream('gzip'));
    return new Uint8Array(await new Response(s).arrayBuffer());
  }
  async function gunzip(u8) {
    const s = new Blob([u8]).stream().pipeThrough(new DecompressionStream('gzip'));
    return new Response(s).text();
  }
  function toB64(u8) {
    let s = '';
    for (let i = 0; i < u8.length; i += 0x8000) s += String.fromCharCode.apply(null, u8.subarray(i, i + 0x8000));
    return btoa(s);
  }
  function fromB64(b64) {
    const bin = atob(b64);
    const u8 = new Uint8Array(bin.length);
    for (let i = 0; i < bin.length; i++) u8[i] = bin.charCodeAt(i);
    return u8;
  }
  L.gzip = gzip; L.gunzip = gunzip; L.toB64 = toB64; L.fromB64 = fromB64;

  // ------------------------------------------------------------------ init + catalog
  L.init = async function () {
    const [db, user] = await Promise.all([N.caps.use('db'), N.caps.use('user')]);
    L.db = db;
    if (user) {
      try { L.uid = await user.id(); } catch (e) { L.uid = null; }
      try { const w = await user.can('data.write'); L.canWrite = w !== false; } catch (e) { L.canWrite = true; }
    }
    L.live = !!(db && L.uid);
    if (db) {
      try {
        db.collection('catalog').onSnapshot(snap => {
          const m = new Map();
          for (const d of snap.docs) { const b = d.data() || {}; if ((b.boards && typeof b.boards === 'object') || (b.models && typeof b.models === 'object')) m.set(d.id, b); }
          L.catalog = m;
          L.ready = true;
          N.bus.emit('library');
        }, err => { console.warn('catalog', err && err.code); L.ready = true; N.bus.emit('library'); });
      } catch (e) { L.ready = true; }
    } else L.ready = true;
    loadDrafts();
    N.bus.emit('library');
  };

  L.whenReady = function (ms) {
    if (L.ready) return Promise.resolve();
    return new Promise(res => {
      const off = N.bus.on('library', () => { if (L.ready) { off(); res(); } });
      setTimeout(() => { off(); res(); }, ms || 8000);
    });
  };

  // every shared board: [{uid, bid, meta}], newest first
  L.list = function () {
    const out = [];
    for (const [uid, doc] of L.catalog) for (const [bid, meta] of Object.entries(doc.boards || {})) if (meta && meta.title) out.push({ uid, bid, meta });
    out.sort((a, b) => (b.meta.updated || 0) - (a.meta.updated || 0));
    return out;
  };
  L.find = function (bid) {
    for (const [uid, doc] of L.catalog) if (doc.boards && doc.boards[bid]) return { uid, bid, meta: doc.boards[bid] };
    return null;
  };
  L.isMine = entry => !!(entry && L.uid && entry.uid === L.uid);

  // ------------------------------------------------------------------ repo-shaped records for the app shell
  const KIND_LABEL = { design: 'Drawn in KiLive', datasheet: 'From a datasheet', kicad: 'KiCad upload' };
  L.kindLabel = meta => (meta.src && meta.src.label) || KIND_LABEL[meta.origin || meta.kind] || 'KiLive board';

  L.toRepo = function (entry, opts) {
    const { uid, bid, meta } = entry;
    const draft = opts && opts.draft;
    const st = meta.stats || {};
    const version = {
      id: 'v1', label: meta.rev > 1 ? 'rev ' + meta.rev : 'rev 1', file: null, latest: true,
      pcbPath: meta.kind === 'kicad' ? (meta.src && meta.src.pcb) || 'uploaded project' : 'generated by KiLive',
      schPath: '', folder: '', kicad: meta.kicad || '8',
      stats: Object.assign({ parts: 0, nets: 0, ics: [] }, st), checks: meta.checks || {}, mask: meta.mask || '#1f6b3a',
      history: [], files: meta.files || [], size: meta.bytes || 0,
    };
    return {
      id: draft ? L.draftRepoId(bid) : L.repoId(bid), user: true, draft: !!draft, uid, bid, kind: meta.kind, origin: meta.origin || meta.kind,
      owner: '', ownerUid: uid, name: meta.title, title: meta.title, desc: meta.desc || '', homepage: meta.homepage || '', license: meta.license || 'CC-BY-4.0',
      stars: 0, forks: 0, topics: meta.tags && meta.tags.length ? meta.tags : [meta.kind === 'kicad' ? 'kicad' : 'noeti-design'],
      url: meta.repoUrl || '', branch: meta.branch || '', head: '', updated: meta.updated ? new Date(meta.updated).toISOString().slice(0, 10) : '', created: meta.created || meta.updated,
      readme: meta.desc || '', meta,
      boards: [{ id: 'main', name: slug(meta.title) || 'board', default: 'v1', versions: [version].concat(
        // earlier revisions kept when the board was updated from KiCad: read-only, newest first
        (draft ? [] : (meta.revs || []).slice().sort((a, b) => b.rev - a.rev)).map(r => Object.assign({}, version, { id: 'r' + r.rev, rev: r.rev, latest: false, label: 'rev ' + r.rev, at: r.at,
          stats: Object.assign({ parts: 0, nets: 0, ics: [] }, { parts: r.parts || 0, nets: r.nets || 0 }), checks: {} }))) }],
    };
  };
  function slug(s) { return String(s || '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 40); }
  L.slug = slug;

  // ------------------------------------------------------------------ read
  L.loadBoard = async function (uid, bid) {
    if (!L.db) throw new Error('The shared library is only available when this page is opened in Claude.');
    const snap = await L.db.doc(`library/${uid}/boards/${bid}`).get();
    if (!snap.exists) throw new Error('This board is no longer in the library.');
    const doc = snap.data();
    const out = { meta: doc.meta, design: doc.design || null, data: null, source: null };
    if (doc.chunks) out.data = JSON.parse(await readBlob(uid, bid, 'd', doc.chunks));
    return out;
  };
  // an earlier revision's board data
  L.loadRevision = async function (uid, bid, rev) {
    if (!L.db) throw new Error('The shared library is only available when this page is opened in Claude.');
    const snap = await L.db.doc(`library/${uid}/boards/${bid}`).get();
    const r = snap.exists ? (snap.data().revs || []).find(x => x.rev === rev) : null;
    if (!r) throw new Error('Revision ' + rev + ' is no longer kept.');
    return JSON.parse(await readBlob(uid, bid, 'r' + rev + '_', r.chunks));
  };
  L.loadSource = async function (uid, bid, n) {
    const b64 = await readChunks(uid, bid, 's', n);
    return fromB64(b64);
  };
  async function readChunks(uid, bid, tag, n) {
    const parts = await Promise.all(Array.from({ length: n }, (_, i) => L.db.doc(`library/${uid}/blobs/${bid}~${tag}${i}`).get()));
    return parts.map(p => { if (!p.exists) throw new Error('Part of this board’s data is missing.'); return p.data().b; }).join('');
  }
  async function readBlob(uid, bid, tag, n) { return gunzip(fromB64(await readChunks(uid, bid, tag, n))); }

  L.thumb = function (uid, bid) {
    if (L.thumbs.has(bid)) return L.thumbs.get(bid);
    const p = (async () => {
      if (!L.db) return null;
      try { const s = await L.db.doc(`library/${uid}/thumbs/${bid}`).get(); return s.exists ? (s.data().img || null) : null; } catch (e) { return null; }
    })();
    L.thumbs.set(bid, p);
    return p;
  };

  // ------------------------------------------------------------------ write (own subtree only)
  let catalogBusy = Promise.resolve();
  function myCatalog() { return JSON.parse(JSON.stringify((L.catalog.get(L.uid) || {}).boards || {})); }
  function myModels() { return JSON.parse(JSON.stringify((L.catalog.get(L.uid) || {}).models || {})); }
  function writeCatalog(mutate, mutateModels) {
    catalogBusy = catalogBusy.then(async () => {
      const boards = myCatalog(), models = myModels();
      if (mutate) mutate(boards);
      if (mutateModels) mutateModels(models);
      const doc = { boards, models, at: Date.now() };
      L.catalog.set(L.uid, doc);
      N.bus.emit('library');
      await L.db.doc('catalog/' + L.uid).set(doc);
    });
    return catalogBusy;
  }
  async function writeChunks(bid, tag, b64, oldN) {
    const n = Math.ceil(b64.length / CHUNK) || 0;
    for (let i = 0; i < n; i++) await L.db.doc(`library/${L.uid}/blobs/${bid}~${tag}${i}`).set({ b: b64.slice(i * CHUNK, (i + 1) * CHUNK) });
    for (let i = n; i < (oldN || 0); i++) { try { await L.db.doc(`library/${L.uid}/blobs/${bid}~${tag}${i}`).delete(); } catch (e) { /* best effort */ } }
    return n;
  }

  /**
   * Save a board to the viewer's own library subtree and list it in the shared catalog.
   * rec = {bid?, meta, design?, data?, source? (Uint8Array zip), thumb? (dataURL)}; onStep(label) for progress.
   */
  L.save = async function (rec, onStep) {
    if (!L.live) throw Object.assign(new Error('offline'), { code: 'offline' });
    const step = s => onStep && onStep(s);
    const bid = rec.bid || L.newId('b');
    const prev = await L.db.doc(`library/${L.uid}/boards/${bid}`).get().catch(() => null);
    const old = prev && prev.exists ? prev.data() : {};
    const now = Date.now();
    const meta = Object.assign({}, rec.meta, { created: (old.meta && old.meta.created) || rec.meta.created || now, updated: now, rev: ((old.meta && old.meta.rev) || 0) + 1 });
    const doc = { meta };
    if (rec.design) doc.design = rec.design;
    // updated from KiCad: the data being replaced stays readable as an earlier revision (the last four are kept)
    let revs = (old.revs || []).slice();
    if (rec.data && rec.keepRevision && old.chunks && old.meta) {
      step('Keeping revision ' + (old.meta.rev || 1) + '…');
      try {
        const prevRev = old.meta.rev || 1, b64 = await readChunks(L.uid, bid, 'd', old.chunks);
        const n = await writeChunks(bid, 'r' + prevRev + '_', b64, 0);
        const st = old.meta.stats || {};
        revs = revs.filter(r => r.rev !== prevRev).concat([{ rev: prevRev, at: old.meta.updated || now, chunks: n, parts: st.parts || 0, nets: st.nets || 0 }]);
        while (revs.length > 4) { const r = revs.shift(); for (let i = 0; i < r.chunks; i++) await L.db.doc(`library/${L.uid}/blobs/${bid}~r${r.rev}_${i}`).delete().catch(() => {}); }
      } catch (e) { console.warn('could not keep the earlier revision', e); }
    }
    if (revs.length) { doc.revs = revs; meta.revs = revs.map(r => ({ rev: r.rev, at: r.at, parts: r.parts, nets: r.nets })); }
    if (rec.data) {
      step('Compressing board data…');
      const gz = await gzip(JSON.stringify(rec.data));
      if (gz.length > MAX_BLOB) throw Object.assign(new Error('too_large'), { code: 'too_large', bytes: gz.length });
      step('Uploading board data…');
      doc.chunks = await writeChunks(bid, 'd', toB64(gz), old.chunks);
      meta.bytes = gz.length;
    }
    if (rec.source && rec.source.length && rec.source.length < 2.5e6) {
      step('Uploading KiCad files…');
      doc.srcChunks = await writeChunks(bid, 's', toB64(rec.source), old.srcChunks);
      meta.hasSource = true;
    }
    if (JSON.stringify(doc).length > 240000) throw Object.assign(new Error('The design is too large to store in one piece.'), { code: 'too_large' });
    step('Saving…');
    await L.db.doc(`library/${L.uid}/boards/${bid}`).set(doc);
    if (rec.thumb) {
      try { await L.db.doc(`library/${L.uid}/thumbs/${bid}`).set({ img: rec.thumb }); meta.hasThumb = true; L.thumbs.set(bid, Promise.resolve(rec.thumb)); } catch (e) { /* the board still saves without a picture */ }
    }
    step('Listing it in the library…');
    await writeCatalog(b => { b[bid] = compactMeta(meta); });
    return { bid, meta };
  };

  L.remove = async function (bid) {
    if (!L.live) throw new Error('offline');
    const snap = await L.db.doc(`library/${L.uid}/boards/${bid}`).get().catch(() => null);
    const doc = snap && snap.exists ? snap.data() : {};
    await writeCatalog(b => { delete b[bid]; });
    for (let i = 0; i < (doc.chunks || 0); i++) await L.db.doc(`library/${L.uid}/blobs/${bid}~d${i}`).delete().catch(() => {});
    for (let i = 0; i < (doc.srcChunks || 0); i++) await L.db.doc(`library/${L.uid}/blobs/${bid}~s${i}`).delete().catch(() => {});
    for (const r of doc.revs || []) for (let i = 0; i < r.chunks; i++) await L.db.doc(`library/${L.uid}/blobs/${bid}~r${r.rev}_${i}`).delete().catch(() => {});
    await L.db.doc(`library/${L.uid}/thumbs/${bid}`).delete().catch(() => {});
    await L.db.doc(`library/${L.uid}/boards/${bid}`).delete();
    L.thumbs.delete(bid);
  };

  // what the explore page needs, kept small (the catalog doc holds all of a user's boards)
  function compactMeta(m) {
    const st = m.stats || {};
    return {
      title: m.title, desc: String(m.desc || '').slice(0, 600), tags: (m.tags || []).slice(0, 8), license: m.license, kind: m.kind, origin: m.origin || m.kind,
      src: m.src || null, created: m.created, updated: m.updated, rev: m.rev, kicad: m.kicad, mask: m.mask, bytes: m.bytes || 0,
      hasThumb: !!m.hasThumb, hasSource: !!m.hasSource, remixOf: m.remixOf || null, revs: (m.revs || []).slice(-4),
      stats: { parts: st.parts || 0, nets: st.nets || 0, w: st.w || 0, h: st.h || 0, layers: st.layers || 0, lines: st.lines || 0, sheets: st.sheets || 0, top: st.top || 0, bottom: st.bottom || 0, ics: (st.ics || []).slice(0, 12).map(x => [x[0], x[1], x[2] || '', '']) },
      checks: m.checks || {}, files: (m.files || []).slice(0, 60),
    };
  }
  L.compactMeta = compactMeta;

  // ------------------------------------------------------------------ drafts (unsaved boards in this browser)
  function loadDrafts() {
    const list = N.store.get(DRAFT_KEY, []);
    for (const d of Array.isArray(list) ? list : []) if (d && d.id && d.design) L.drafts.set(d.id, d);
  }
  function persistDrafts() {
    const keep = [...L.drafts.values()].filter(d => d.design).slice(-8).map(d => ({ id: d.id, bid: d.bid || null, meta: d.meta, design: d.design, at: d.at }));
    N.store.set(DRAFT_KEY, keep);
  }
  // part models people made for the live simulation (what each pin of a chip does), shared with everyone
  L.models = function () {
    const out = [];
    for (const [uid, doc] of L.catalog) for (const m of Object.values(doc.models || {})) if (m && m.match && m.roles) out.push(Object.assign({ by: uid }, m));
    return out;
  };
  L.saveModel = async function (m) {
    if (!L.db || !L.uid) throw new Error('The shared library is only available when this page is opened in Claude.');
    const clean = { id: String(m.id), match: String(m.match).slice(0, 80), name: String(m.name || '').slice(0, 80), note: String(m.note || '').slice(0, 200), roles: m.roles, pins: m.pins || 0, at: Date.now() };
    if (JSON.stringify(clean).length > 24000) throw new Error('This model is too large to share.');
    await writeCatalog(null, models => { for (const [k, x] of Object.entries(models)) if (x && x.match === clean.match) delete models[k]; models[clean.id] = clean; });
  };
  L.putDraft = function (d) { d.at = Date.now(); L.drafts.set(d.id, d); persistDrafts(); return d; };
  L.getDraft = id => L.drafts.get(id) || null;
  L.dropDraft = function (id) { L.drafts.delete(id); persistDrafts(); };
  L.saveDraftSoon = N.debounce(() => persistDrafts(), 600);
})();
