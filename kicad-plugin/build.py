"""Embed the plugin sources in the web app (js/kicadplugin-src.js): the page zips them on demand."""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
src = {
    'swig/__init__.py': 'swig/__init__.py',
    'swig/noeti_send.py': 'swig/noeti_send.py',
    'swig/noeti_common.py': 'swig/noeti_common.py',
    'ipc/main.py': 'ipc/main.py',
    'ipc/noeti_common.py': 'swig/noeti_common.py',
    'ipc/plugin.json': 'ipc/plugin.json',
    'ipc/requirements.txt': 'ipc/requirements.txt',
}
out = {k: open(os.path.join(here, v), encoding='utf-8').read() for k, v in src.items()}
js = "/* generated by kicad-plugin/build.py - the Send to KiLive KiCad plugin sources */\nwindow.Noeti = window.Noeti || {};\nwindow.Noeti.kicadPluginSrc = " + json.dumps(out, indent=0) + ";\n"
open(os.path.join(here, '..', 'app', 'js', 'kicadplugin-src.js'), 'w', encoding='utf-8').write(js)
print('wrote', len(js), 'bytes')
